function X = Fun_bound_reflect01(X)
%FUN_BOUND_REFLECT01  将实数矩阵 X 映射到区间 [0,1]（反射边界）。
%
% 为什么不用简单的 clamp(x,0,1)？
%   clamp 会在边界处“挤压”分布，导致 CMA-ES 的协方差学习被扭曲，
%   进而更容易早熟或卡边界。
%
% 反射映射（period=2）：
%   u = mod(x,2)  -> [0,2)
%   if u>1 => u = 2-u
% 这样可以保证：
%   1) 输出始终在 [0,1]
%   2) 分布在边界处更平滑（相当于镜像扩展）
%
% 输入：
%   X : 任意维度实数矩阵
% 输出：
%   X : 同维度，且所有元素属于 [0,1]

X = mod(X, 2);
idx = X > 1;
X(idx) = 2 - X(idx);

% 数值安全：避免出现 -0 或 1+eps
X(X < 0) = 0;
X(X > 1) = 1;
end
