%%
%  1/4圆弧段 + 幂函数过渡

    n  = 51;      %质心线插值点数量，影响建模和误差计算   注：如果计算角度的点位于中点等特殊位置，应当采用特定的数值（如中点应令n为奇数）
    r  = 50 ;     %组装所用的圆筒半径   【问题：基底变形的半径变化？】
    TYPE = 2;     %待优化的变量类型个数，宽度与角度各算一类  【宽度、扭转角、随机旋转角度】
