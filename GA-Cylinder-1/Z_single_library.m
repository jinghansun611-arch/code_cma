    FEA.cpus      = 1 ; 
    FEA.P1_AZ = r + 0.1;
    FEA.P2_AZ = 0 ;
%函数输入  ：  三线框架-完美（1：左支撑  2：右支撑  3：中拱）
    
    x = 5;  %三轴放大系数
    y = 5;
    z = 7.5;
    r = 40;
    p1 = 80  ;     %参数1 ：线3长度
    p2 = 20 ;      %参数2  ：幂函数段  Z轴放大系数
    p3 = 5 ;       %参数3  ：三角函数段Z轴放大系数
    p4 = pi/15 ;   %参数4  ：YZ面角度
    t_lim  = [  0 , 1 , 9, 10 ];
