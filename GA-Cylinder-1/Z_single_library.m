%即：绘图时目标曲线直接绘图，仿真结果需要整体下移 r 
    funr = r + z * ( 1 + cos( -pi + 2*pi*t) ) ;
    twist = pi/2 - pi * t / 6 ; % 扭转15°
    
    funx = [ x * t ,...
             r * ( cos( 0.75*pi - (t-1)*pi/16 ) - cos(0.75*pi) ) + x ,...
             x * (t-9) + x + 2*r*cos(0.25*pi) ];
    funy = [ 0*t ,...
             0*t ,...
             0*t  ];
